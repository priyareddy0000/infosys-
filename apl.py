def get_user_history(user_email):
    conn = sqlite3.connect(DB_PATH)
    c = conn.cursor()
    c.execute('''SELECT query_text, language, generated_code, timestamp FROM queries
                 WHERE user_email=? ORDER BY timestamp DESC''', (user_email,))
    history = c.fetchall()
    conn.close()
    return history

