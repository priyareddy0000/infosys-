import sqlite3

DB_PATH = "yourapp.db"

def init_db():
    conn = sqlite3.connect(DB_PATH)
    c = conn.cursor()
    c.execute('''
        CREATE TABLE IF NOT EXISTS users (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            email TEXT UNIQUE, password TEXT, role TEXT
        )''')
    c.execute('''
        CREATE TABLE IF NOT EXISTS queries (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            user_email TEXT,
            query_text TEXT,
            language TEXT,
            generated_code TEXT,
            timestamp TEXT
        )''')
    c.execute('''
        CREATE TABLE IF NOT EXISTS feedback (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            user_email TEXT,
            query_id INTEGER,
            rating INTEGER,
            comment TEXT,
            timestamp TEXT
        )''')
    conn.commit()
    conn.close()
init_db()

