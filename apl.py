def get_trending_queries():
    conn = sqlite3.connect(DB_PATH)
    df = pd.read_sql_query(
        "SELECT query_text, COUNT(*) as count FROM queries GROUP BY query_text ORDER BY count DESC LIMIT 5",
        conn)
    conn.close()
    return df

def get_language_stats():
    conn = sqlite3.connect(DB_PATH)
    df = pd.read_sql_query(
        "SELECT language, COUNT(*) as count FROM queries GROUP BY language ORDER BY count DESC",
        conn)
    conn.close()
    return df

def get_feedback_stats():
    conn = sqlite3.connect(DB_PATH)
    df = pd.read_sql_query(
        "SELECT rating, COUNT(*) as count FROM feedback GROUP BY rating ORDER BY rating",
        conn)
    avg = pd.read_sql_query("SELECT AVG(rating) as avg_rating FROM feedback", conn).iloc[0, 0]
    conn.close()
    return df, avg

